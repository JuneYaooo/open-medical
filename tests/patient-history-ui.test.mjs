import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, mkdirSync } from 'node:fs';
import { chromium } from 'playwright-core';
import { fixture } from './helpers.mjs';
const chrome = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';

test('diagnosis workspace preserves uncertainty, filters records, follows sources and saves sourced history', {skip:!existsSync(chrome)}, async t => {
  const f = await fixture(t);
  const clinicalSummary = {text:'2025 年初出现反复不适，就诊后开始持续随访。2026 年复查发现部分指标变化，仍需进一步核对。\n既往治疗、检查结果与症状变化见原始记录。尚不能据此确认新的诊断。',source:'病史验证.txt 第1–3行'};
  const p=(await f.json('/api/patients','POST', {name:'病史界面验证（合成）',clinicalSummary,note:'报告日期待核对，勿作为病史结论。',tags:['定期随访'],diagnoses:[
    {name:'已明确的既往问题',status:'confirmed',code:'Z00',date:'2025-01-02',note:'依据既往就诊记录登记。',source:'病史验证.txt 第1行'},
    {name:'疑似问题，尚待排查',date:'2026-03-02',source:'病史验证.txt 第2行'},
    {name:'影像检查发现',status:'finding',date:'2026-06-08',note:'结合原始报告与复查情况判断。'},
    {name:'诊断名称待核对',status:'needs_review',note:'不同资料中的表述不一致。'},
  ],visits:Array.from({length:6},(_,i)=>({date:`2026-0${i+1}-08`,reason:`第 ${i+1} 次随访记录`,note:'症状与检查情况已记录，后续结合复查判断。',source:'病史验证.txt 第3行'}))})).data;
  const empty=(await f.json('/api/patients','POST',{name:'病史空档案验证（合成）'})).data;
  await f.json(`/api/sessions/${p.sessionId}/files`,'POST',{name:'病史验证.txt',text:'合成原始病史记录；保留疑似与待核对表述。'});
  const browser=await chromium.launch({executablePath:chrome,headless:true});t.after(()=>browser.close());
  const page=await browser.newPage({viewport:{width:1440,height:2400}});page.setDefaultTimeout(15000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const panel=page.getByRole('region',{name:'患者资料面板'});
  const url=`${f.origin}/?view=patients&patient=${p.id}&tab=diagnoses`;
  await page.goto(url);
  await panel.getByRole('heading',{name:'诊断与病史',exact:true}).waitFor();
  const problems=panel.getByRole('region',{name:'诊断列表',exact:true});
  assert.equal(await problems.locator('.history-diagnosis-title').count(),2);
  assert.equal(await panel.locator('.history-original[open]').count(),0);
  assert.doesNotMatch(await panel.innerText(),/诊断名称待核对|报告日期待核对/);
  assert.doesNotMatch((await panel.locator('.clinical-summary-text').allTextContents()).join(''),/报告日期待核对/);
  await panel.getByRole('navigation',{name:'诊断分类'}).getByRole('button',{name:/疑似待排/}).click();
  assert.equal(await problems.locator('.history-diagnosis-title').count(),1);
  assert.match(await problems.innerText(),/疑似问题，尚待排查/);
  await problems.getByRole('button',{name:'清除筛选'}).click();
  await panel.getByRole('searchbox',{name:'搜索诊断与病史记录'}).fill('Z00');
  assert.equal(await problems.locator('.history-diagnosis-title').count(),1);
  await panel.getByRole('searchbox',{name:'搜索诊断与病史记录'}).fill('不存在的诊断');
  await problems.getByText('没有符合条件的诊断记录').waitFor();
  await problems.getByRole('button',{name:'清除筛选'}).click();
  await page.getByRole('button',{name:'资料核对',exact:true}).click();
  await panel.getByRole('region',{name:'待核对记录'}).waitFor();
  assert.match(await panel.innerText(),/诊断名称待核对|报告日期待核对/);
  await page.reload();
  await panel.getByRole('region',{name:'待核对记录'}).waitFor();
  await page.getByRole('button',{name:'诊断与病史',exact:true}).click();
  const timeline=panel.getByRole('region',{name:'病程时间线'});
  assert.equal(await timeline.locator('time').count(),4);
  assert.equal(await timeline.locator('time').first().innerText(),'2026-06-08');
  await timeline.getByRole('button',{name:'展开其余 2 次就诊'}).click();
  assert.equal(await timeline.locator('time').count(),6);
  await timeline.getByRole('button',{name:'收起较早记录'}).click();
  const summary=panel.getByRole('region',{name:'病史摘要',exact:true});
  await summary.getByText('查看既有病史记录与来源',{exact:true}).click();
  await summary.getByText('资料来源 · 1',{exact:true}).click();
  await summary.getByRole('button',{name:'查看原文',exact:true}).click();
  const library=panel.getByRole('region',{name:'资料库',exact:true});
  await library.getByText('查看文字内容',{exact:true}).waitFor();
  assert.equal(await library.locator('.chart-files>details[open]').count(),1);
  await page.goto(url);
  await panel.getByRole('button',{name:'编辑摘要',exact:true}).click();
  await panel.getByRole('textbox',{name:'当前状态'}).fill('复诊后更新摘要。疑似问题仍待排查，尚未确诊。');
  await panel.getByRole('textbox',{name:'主要问题'}).fill('反复不适，影响睡眠。');
  await panel.getByRole('textbox',{name:'病程演变'}).fill('年初起病，治疗后改善，近期再次不适。');
  await panel.getByRole('textbox',{name:'病史摘要来源'}).fill('医生本次问诊记录');
  await panel.getByRole('button',{name:'保存摘要'}).click();
  await panel.getByText('复诊后更新摘要。疑似问题仍待排查，尚未确诊。',{exact:true}).waitFor();
  await page.reload();
  await panel.getByText('复诊后更新摘要。疑似问题仍待排查，尚未确诊。',{exact:true}).waitFor();
  const saved=(await f.json('/api/patients/'+p.id)).data;
  assert.equal(saved.clinicalSummary.source,'医生本次问诊记录');
  assert.deepEqual(saved.diagnoses,p.diagnoses);
  assert.equal(saved.note,p.note);
  await panel.getByRole('button',{name:'编辑诊断'}).click();
  assert.equal(await page.getByRole('combobox',{name:'疑似问题，尚待排查诊断状态'}).inputValue(),'suspected');
  await panel.getByRole('button',{name:'返回记录'}).click();
  mkdirSync('output/playwright',{recursive:true});
  await panel.screenshot({path:'output/playwright/patient-history-desktop.png'});
  await page.setViewportSize({width:760,height:2400});
  assert.ok(await page.locator('.patient-history-workspace').evaluate(el=>el.scrollWidth<=el.clientWidth+1));
  await panel.screenshot({path:'output/playwright/patient-history-narrow.png'});
  await panel.getByRole('button',{name:'查看治疗方案与预后',exact:true}).click();
  await panel.getByRole('heading',{name:'治疗方案与预后',exact:true}).waitFor();
  assert.ok(page.url().includes(p.id));
  await page.goto(`${f.origin}/?view=patients&patient=${empty.id}&tab=diagnoses`);
  await panel.getByRole('region',{name:'病史摘要',exact:true}).waitFor();
  await panel.getByRole('button',{name:'补充摘要',exact:true}).click();
  await panel.getByRole('textbox',{name:'当前状态'}).fill('首次问诊记录');
  await panel.getByRole('textbox',{name:'主要问题'}).fill('症状尚未记录');
  await panel.getByRole('textbox',{name:'病程演变'}).fill('既往经过尚未记录');
  assert.equal(await panel.getByRole('button',{name:'保存摘要'}).isDisabled(),true);
  await panel.getByRole('textbox',{name:'病史摘要来源'}).fill('医生问诊');
  await panel.getByRole('button',{name:'保存摘要'}).click();
  await panel.getByText('首次问诊记录',{exact:true}).waitFor();
  const current=(await f.json('/api/patients/'+empty.id)).data;
  const longText='既往病史按原始记录保留，疑似问题仍待进一步核对。'.repeat(25);
  await f.json('/api/patients/'+empty.id,'PATCH',{expectedRevision:current.revision,clinicalSummary:{text:longText,source:'合成长病史记录'}});
  await page.reload();
  assert.equal(await panel.locator('.history-original[open]').count(),0);
  await panel.getByText('查看既有病史记录与来源',{exact:true}).click();
  assert.equal(await panel.locator('.history-summary-copy').innerText(),longText);
  await panel.getByText('查看既有病史记录与来源',{exact:true}).click();
  assert.equal(await panel.locator('.history-original[open]').count(),0);
  assert.deepEqual(errors,[]);
});
