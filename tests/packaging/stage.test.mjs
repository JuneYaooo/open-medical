import test from "node:test";
import assert from "node:assert/strict";
import {
  existsSync,
  mkdtempSync,
  readdirSync,
  realpathSync,
  rmSync,
} from "node:fs";
import { mkdir, symlink, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, relative, resolve, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import {
  desktopRuntimeEntries,
  excludedPluginPath,
  stageRuntime,
} from "../../scripts/runtime-stage.mjs";

const ROOT = fileURLToPath(new URL("../..", import.meta.url));
const PLUGINS = join(ROOT, "plugins");

function tempDirectory(prefix) {
  // Match the repository's other tests: prefer the configured temp dir, then
  // fall back to the platform default if it is read-only in the runner.
  for (const base of [process.env.MEDICAL_TEST_TMP, tmpdir(), "/tmp"]) {
    if (!base) continue;
    try {
      return mkdtempSync(join(base, prefix));
    } catch (error) {
      if (!["ENOENT", "EROFS", "EACCES", "EPERM"].includes(error.code))
        throw error;
    }
  }
  throw new Error("无法创建打包测试临时目录");
}

async function listFiles(directory) {
  const files = [];
  const visit = async (current) => {
    for (const entry of await readdirSync(current, { withFileTypes: true })) {
      const absolute = join(current, entry.name);
      if (entry.isDirectory()) await visit(absolute);
      else if (entry.isFile())
        files.push(relative(directory, absolute).split(sep).join("/"));
    }
  };
  await visit(directory);
  return files.sort();
}

function sourcePluginIds() {
  return readdirSync(PLUGINS, { withFileTypes: true })
    .filter(
      (entry) =>
        entry.isDirectory() && existsSync(join(PLUGINS, entry.name, "plugin.mjs")),
    )
    .map((entry) => entry.name)
    .sort();
}

test("桌面打包 stage 包含运行时插件但排除测试资产", async (t) => {
  const stage = await tempDirectory("omw-package-stage-");
  t.after(() => rmSync(stage, { recursive: true, force: true }));

  // build/icons is generated by npm run build; npm test can run before it.
  await stageRuntime({
    root: ROOT,
    target: stage,
    entries: desktopRuntimeEntries.filter((entry) =>
      existsSync(join(ROOT, entry)),
    ),
  });

  const sourceFiles = await listFiles(PLUGINS);
  const expectedPluginFiles = sourceFiles.filter(
    (path) => !excludedPluginPath(path),
  );
  const stagedPluginFiles = await listFiles(join(stage, "plugins"));
  assert.deepEqual(
    stagedPluginFiles,
    expectedPluginFiles,
    "stage 必须包含源码 plugins/ 的全部运行时文件，且不能多出测试资产",
  );

  const staged = new Set(stagedPluginFiles);
  for (const id of sourcePluginIds()) {
    assert.ok(staged.has(`${id}/plugin.mjs`), `${id}/plugin.mjs 必须打包`);
    for (const file of expectedPluginFiles.filter((path) =>
      path.startsWith(`${id}/`),
    ))
      assert.ok(staged.has(file), `${file} 必须打包`);
  }

  // Every plugin entrypoint, migration, server module and prompt that exists in
  // source must be present with the same bytes. This would have caught the
  // original missing plugins/ allowlist even before booting the server.
  for (const file of expectedPluginFiles)
    assert.equal(
      existsSync(join(stage, "plugins", file)),
      true,
      `${file} 必须存在`,
    );

  for (const file of stagedPluginFiles) {
    assert.doesNotMatch(
      file,
      /(^|\/)(?:tests?|fixtures|__tests__|__mocks__|__snapshots__|__screenshots__|screenshots?|snapshots?)(\/|$)/i,
      `测试目录不应打包：${file}`,
    );
    assert.doesNotMatch(
      file,
      /(?:^|[._-])(?:test|spec)(?:[._-]|$)/i,
      `测试文件不应打包：${file}`,
    );
    assert.doesNotMatch(
      file,
      /(^|\/)\.env(?:\.|$)/i,
      `.env 不应打包：${file}`,
    );
    assert.doesNotMatch(
      file,
      /\.(?:sqlite(?:3)?|db)(?:-(?:wal|shm))?$/i,
      `数据库文件不应打包：${file}`,
    );
    assert.doesNotMatch(
      file,
      /(?:screens?shot|截图)/i,
      `截图不应打包：${file}`,
    );
  }
  assert.equal(existsSync(join(stage, "plugins", "channel-fake")), false);
  assert.equal(existsSync(join(stage, "docs", "plugin-template")), false);

  // The packaged server resolves plugins from its own directory, not cwd.
  symlink(
    join(ROOT, "node_modules"),
    join(stage, "node_modules"),
    process.platform === "win32" ? "junction" : "dir",
  );

  const previousPluginDirs = process.env.MEDICAL_PLUGIN_DIRS;
  const previousHome = process.env.HOME;
  const previousUserProfile = process.env.USERPROFILE;
  const previousTmpDir = process.env.TMPDIR;
  delete process.env.MEDICAL_PLUGIN_DIRS;
  // createServer's :memory: credential vault lives under homedir, and LanceDB
  // spills through TMPDIR. Isolate both in the stage so the test never writes
  // into the real user profile or a read-only runner temp directory.
  const testHome = join(stage, "home");
  const testTmp = join(stage, "tmp");
  await mkdir(testHome, { recursive: true });
  await mkdir(testTmp, { recursive: true });
  process.env.HOME = testHome;
  process.env.TMPDIR = testTmp;
  if (process.platform === "win32") process.env.USERPROFILE = testHome;
  t.after(() => {
    if (previousPluginDirs === undefined)
      delete process.env.MEDICAL_PLUGIN_DIRS;
    else process.env.MEDICAL_PLUGIN_DIRS = previousPluginDirs;
    if (previousHome === undefined) delete process.env.HOME;
    else process.env.HOME = previousHome;
    if (previousUserProfile === undefined) delete process.env.USERPROFILE;
    else process.env.USERPROFILE = previousUserProfile;
    if (previousTmpDir === undefined) delete process.env.TMPDIR;
    else process.env.TMPDIR = previousTmpDir;
  });

  const { createServer } = await import(
    pathToFileURL(join(stage, "server", "agent.mjs")).href
  );
  const server = createServer({
    database: ":memory:",
    provider: {
      provider: "packaging-test",
      model: "packaging-test",
      apiKey: "packaging-test",
      complete: async () => {
        throw new Error("打包测试不应调用模型");
      },
    },
  });
  t.after(() => server.shutdown());
  await new Promise((resolveListen, reject) => {
    server.once("error", reject);
    server.listen(0, "127.0.0.1", resolveListen);
  });

  // Compare real paths: macOS temp dirs sit behind the /var -> /private/var link.
  assert.equal(
    realpathSync(server.pluginHost.pluginDirs[0]),
    realpathSync(resolve(stage, "plugins")),
    "打包后的默认插件目录必须是 stage/plugins",
  );

  const { port } = server.address();
  const response = await fetch(`http://127.0.0.1:${port}/api/plugins`, {
    headers: { "x-medical-token": server.token },
  });
  assert.equal(response.status, 200);
  const { plugins } = await response.json();
  const ids = sourcePluginIds();
  assert.deepEqual(
    plugins.map((plugin) => plugin.id).sort(),
    ids,
    "打包后的插件列表必须与源码 plugins/ 目录一致",
  );
  assert.deepEqual(
    plugins.map((plugin) => ({ id: plugin.id, status: plugin.status })),
    // 非核心插件在全新安装里默认停用，其余必须 ready。
    ids.map((id) => ({ id, status: ["drg", "research-stats", "trials"].includes(id) ? "disabled" : "ready" })),
    "打包后核心领域插件必须 ready，非核心插件默认停用",
  );
  assert.equal(
    plugins.some((plugin) => plugin.id === "channel-fake"),
    false,
    "测试插件不应进入安装包",
  );
});

test("插件过滤规则拒绝 tests/fixtures/截图/密钥/数据库", async (t) => {
  const source = await tempDirectory("omw-package-probe-");
  const stage = await tempDirectory("omw-package-probe-stage-");
  t.after(() => rmSync(source, { recursive: true, force: true }));
  t.after(() => rmSync(stage, { recursive: true, force: true }));

  const plugin = join(source, "plugins", "probe");
  await mkdir(join(plugin, "test"), { recursive: true });
  await mkdir(join(plugin, "tests"), { recursive: true });
  await mkdir(join(plugin, "fixtures"), { recursive: true });
  await mkdir(join(plugin, "screenshots"), { recursive: true });
  await mkdir(join(plugin, "migrations"), { recursive: true });
  await mkdir(join(plugin, "server"), { recursive: true });
  await mkdir(join(plugin, "ui"), { recursive: true });
  await writeFile(join(source, ".env.example"), "AI_PROVIDER=\n");
  for (const file of [
    "plugin.mjs",
    "prompt.md",
    "migrations/001_init.sql",
    "server/impl.mjs",
    "ui/index.jsx",
  ])
    await writeFile(join(plugin, file), "// runtime\n");
  for (const file of [
    "test/probe.test.mjs",
    "tests/helper.mjs",
    "fixtures/sample.json",
    "screenshots/home.png",
    "server/impl.test.mjs",
    "ui/Case.spec.jsx",
    "test-utils.mjs",
    ".env",
    "state.sqlite",
  ])
    await writeFile(join(plugin, file), "excluded\n");

  await stageRuntime({ root: source, target: stage, entries: ["plugins"], scripts: [] });

  assert.deepEqual(await listFiles(join(stage, "plugins")), [
    "probe/migrations/001_init.sql",
    "probe/plugin.mjs",
    "probe/prompt.md",
    "probe/server/impl.mjs",
    "probe/ui/index.jsx",
  ]);
});
