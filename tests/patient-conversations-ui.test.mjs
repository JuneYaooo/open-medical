import test from "node:test";
import assert from "node:assert/strict";
import { existsSync, mkdirSync } from "node:fs";
import { chromium } from "playwright-core";
import { fixture } from "./helpers.mjs";
const chrome="/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";
test("patient question UI: new question, follow-up, history, reload and patient switch", {skip:!existsSync(chrome)||!existsSync("dist/index.html")}, async t=>{
 const inputs=[];
 const provider={provider:"stub",model:"stub",apiKey:"stub",async complete(messages){inputs.push(structuredClone(messages));return {message:{role:"assistant",content:"这是合成回答，已收到本次问题。"}};}};
 const f=await fixture(t,{provider,followupOptions:{autoStart:false}});
 for(const name of ["问答测试甲","问答测试乙"])await f.json("/api/patients","POST",{name});
 const browser=await chromium.launch({executablePath:chrome,headless:true});t.after(()=>browser.close());
 const page=await browser.newPage({viewport:{width:1380,height:940}});
 const errors=[];page.on("pageerror",e=>errors.push(e.message));
 await page.goto(f.origin+"/?view=patients");
 await page.locator(".patient-card",{hasText:"问答测试甲"}).click();
 await page.getByRole("button",{name:"打开病例工作区",exact:true}).click();
 await page.getByText("问一个新问题",{exact:true}).waitFor();
 async function send(message){
  await page.getByRole("textbox",{name:"医疗工作需求",exact:true}).fill(message);
  await page.getByRole("button",{name:"发送任务",exact:true}).click();
  await page.locator(".patient-question-context").filter({hasText:"继续追问"}).waitFor();
 }
 await send("问题甲：总结本次记录");
 await send("继续解释甲项");
 assert.ok(JSON.stringify(inputs.at(-1)).includes("问题甲"));
 assert.equal(await page.locator(".user-message").count(),2);
 await page.getByRole("textbox",{name:"医疗工作需求",exact:true}).fill("草稿甲");
 await page.getByRole("button",{name:"＋ 问新问题",exact:true}).click();
 assert.equal(await page.locator(".user-message").count(),0);
 await page.getByRole("textbox",{name:"医疗工作需求",exact:true}).fill("草稿乙");
 await page.locator(".patient-question-history summary").click();
 await page.locator(".patient-question-history button",{hasText:"问题甲"}).click();
 assert.equal(await page.getByRole("textbox",{name:"医疗工作需求",exact:true}).inputValue(),"草稿甲");
 await page.getByRole("button",{name:"＋ 问新问题",exact:true}).click();
 assert.equal(await page.getByRole("textbox",{name:"医疗工作需求",exact:true}).inputValue(),"草稿乙");
 await send("问题乙：总结另一个方面");
 assert.ok(!JSON.stringify(inputs.at(-1)).includes("问题甲"));
 assert.equal(await page.locator(".user-message").count(),1);
 await page.locator(".patient-question-history summary").click();
 await page.locator(".patient-question-history button",{hasText:"问题甲"}).click();
 assert.equal(await page.locator(".user-message").count(),2);
 await send("再追问甲项");
 assert.ok(!JSON.stringify(inputs.at(-1)).includes("问题乙"));
 mkdirSync("output/patient-questions",{recursive:true});
 await page.screenshot({path:"output/patient-questions/follow-up.png",fullPage:false});
 await page.reload();
 // Refresh now restores the task directly instead of dropping back to the patient list.
 await page.getByRole("textbox",{name:"医疗工作需求",exact:true}).waitFor();
 assert.equal(new URL(page.url()).searchParams.get("view"),"workbench");
 await page.locator(".patient-question-history summary").click();
 await page.locator(".patient-question-history button",{hasText:"问题甲"}).click();
 await page.locator(".user-message").filter({hasText:"再追问甲项"}).waitFor();
 assert.equal(await page.locator(".user-message").count(),3);
 await page.getByRole("button",{name:"患者",exact:true}).click();
 if(await page.getByRole("button",{name:"返回列表",exact:true}).count()) await page.getByRole("button",{name:"返回列表",exact:true}).click();
 await page.locator(".patient-card",{hasText:"问答测试乙"}).click();
 await page.getByRole("button",{name:"打开病例工作区",exact:true}).click();
 assert.equal(await page.locator(".user-message").count(),0);
 assert.equal(await page.locator(".patient-question-history").count(),0);
 assert.deepEqual(errors,[]);
});
