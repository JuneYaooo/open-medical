import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, mkdirSync } from 'node:fs';
import { chromium } from 'playwright-core';
import { fixture } from './helpers.mjs';
const chrome = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';

test('review tab isolates conflicts and import failures, opens text repair, and persists corrections', {skip:!existsSync(chrome)}, async t=>{
  const f=await fixture(t);
  const p=(await f.json('/api/patients','POST',{name:'资料核对验证（合成）',note:'报告日期存在冲突。',diagnoses:[{name:'待核对的诊断',status:'needs_review',source:'报告.txt 第1行'}],labs:[{item:'合成指标',value:1,unit:'U/L',date:'2026-01-01',source:'报告.txt 第2行'},{item:'合成指标',value:2,unit:'U/L',date:'2026-01-01',source:'报告.txt 第3行'}]})).data;
  const text=(await f.json(`/api/sessions/${p.sessionId}/files`,'POST',{name:'报告.txt',text:'合成来源文本'})).data;
  const image=(await f.json(`/api/sessions/${p.sessionId}/files`,'POST',{name:'扫描.png',image:'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg=='})).data;
  f.server.workspaces.store.update(p.sessionId,w=>{
    const file=w.materials.find(x=>x.id===image.id);
    file.text='???';file.extraction.ocr={status:'ready',method:'local-ocr',quality:{level:'poor',score:1}};
  });
  f.server.sessionBridge.saveIntakeIssues(p.sessionId,[{name:'未导入.pdf',stage:'upload',error:'文件读取失败，请重新上传。'}]);
  const browser=await chromium.launch({executablePath:chrome,headless:true});t.after(()=>browser.close());
  const page=await browser.newPage({viewport:{width:1440,height:1700}});page.setDefaultTimeout(15000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(`${f.origin}/?view=patients&patient=${p.id}&tab=review`);
  const panel=page.getByRole('region',{name:'患者资料面板'});
  await panel.getByRole('heading',{name:'资料核对',exact:true}).waitFor();
  assert.match(await panel.getByRole('region',{name:'检验数值冲突'}).innerText(),/1 U\/L[\s\S]*2 U\/L/);
  assert.match(await panel.getByRole('region',{name:'资料导入与识别'}).innerText(),/未导入.pdf/);
  await panel.getByRole('region',{name:'待核对记录'}).getByRole('button',{name:'查看原文'}).click();
  assert.equal(await panel.locator('.chart-files>details[open]').count(),1);
  assert.match(await panel.locator('.chart-files>details[open]').innerText(),new RegExp(text.name));
  assert.equal(await panel.locator('.ocr-review-banner').count(),0);
  await page.getByRole('button',{name:'资料核对',exact:true}).click();
  await panel.getByText('扫描.png',{exact:false}).first().click();
  await panel.getByRole('button',{name:'修正文字',exact:true}).click();
  const editor=panel.getByRole('textbox',{name:'修正 扫描.png 的识别文本'});
  await editor.fill('合成患者记录：2026年1月1日复诊，症状改善。此文本仅供界面验证。');
  await panel.getByRole('button',{name:'保存修正'}).click();
  await page.waitForFunction(()=>!document.querySelector('textarea[aria-label="修正 扫描.png 的识别文本"]'));
  assert.match((await f.json(`/api/sessions/${p.sessionId}`)).data.files.find(x=>x.id===image.id).text,/症状改善/);
  await panel.getByRole('button',{name:'编辑备注'}).click();
  await panel.getByRole('textbox',{name:'资料核对备注'}).fill('已核对报告日期。');
  await panel.getByRole('button',{name:'保存备注'}).click();
  await panel.getByText('已核对报告日期。',{exact:true}).waitFor();
  await page.reload();await panel.getByText('已核对报告日期。',{exact:true}).waitFor();
  mkdirSync('output/playwright',{recursive:true});
  await panel.screenshot({path:'output/playwright/patient-review-desktop.png'});
  await page.setViewportSize({width:760,height:1700});
  assert.ok(await panel.evaluate(el=>el.scrollWidth<=el.clientWidth+1));
  await panel.getByRole('button',{name:'修正诊断记录'}).click();
  await panel.getByRole('combobox',{name:'待核对的诊断诊断状态'}).selectOption('confirmed');
  await page.waitForFunction(()=>document.querySelector('select[aria-label="待核对的诊断诊断状态"]')?.value==='confirmed');
  await panel.getByRole('button',{name:'返回资料核对'}).click();
  await panel.getByText('暂无标为待核对的记录。').waitFor();
  assert.equal((await f.json(`/api/patients/${p.id}`)).data.diagnoses[0].status,'confirmed');
  assert.deepEqual(errors,[]);
});
