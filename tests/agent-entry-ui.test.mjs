test('project entry creates a separate conversation and runs the submitted goal once',{skip},async t=>{
  const {page,origin,json}=await setup(t,{provider:{apiKey:'synthetic',model:'entry-test',async complete(){return {message:{role:'assistant',content:'ENTRY_TASK_DONE'}};}}});
  const root=mkdtempSync(join(tmpdir(),'agent-entry-'));t.after(()=>rmSync(root,{recursive:true,force:true}));
  const project=(await json('/api/workspaces','POST',{root,title:'入口合成项目',directoryConsent:true})).data;
  await page.goto(origin);
  await page.getByRole('combobox',{name:'任务关联项目'}).selectOption(project.id);
  await page.getByRole('textbox',{name:'任务内容',exact:true}).fill('仅回答你好，不操作文件。');
  const created=page.waitForResponse(r=>r.url().endsWith(`/workspaces/${project.id}/tasks`)&&r.request().method()==='POST');
  await page.getByRole('button',{name:'发送任务',exact:true}).click();
  const child=await(await created).json();assert.notEqual(child.id,project.id);
  await page.waitForURL(url=>url.searchParams.get('workspace')===child.id);
  await page.getByText('ENTRY_TASK_DONE',{exact:true}).first().waitFor();
  const detail=(await json('/api/workspaces/'+child.id)).data;
  assert.equal(detail.runs.length,1);assert.equal(detail.messages.filter(m=>m.role==='user').length,1);
  assert.equal((await json('/api/workspaces/'+project.id)).data.runs.length,0);
});
