import test from 'node:test';
import assert from 'node:assert/strict';
import {existsSync,mkdtempSync,writeFileSync,rmSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {chromium} from 'playwright-core';
import {fixture} from './helpers.mjs';
const chrome='/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
test('V6 uses real navigation, project identity, task history and display modes without changing data', {skip:!existsSync(chrome)},async t=>{
 const root=mkdtempSync(join(tmpdir(),'om-v6-'));t.after(()=>rmSync(root,{recursive:true,force:true}));writeFileSync(join(root,'note.md'),'# 合成项目文件\n\n保持原文。');
 const f=await fixture(t),browser=await chromium.launch({executablePath:chrome,headless:true});t.after(()=>browser.close());
 const a=(await f.json('/api/workspaces','POST',{root,title:'项目甲',directoryConsent:true})).data;
 const b=(await f.json('/api/workspaces','POST',{root,title:'项目乙',directoryConsent:true})).data;
 const session=await f.session('持续任务验收');
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(f.origin);await page.getByRole('heading',{name:'这次需要做什么？'}).waitFor();
 const nav=page.getByRole('navigation',{name:'通用工作'});
 assert.deepEqual(await nav.getByRole('button').allTextContents(),['任务','项目','工具']);
 assert.equal(await page.locator('.advanced-nav').getAttribute('open'),null);
 await page.screenshot({path:'output/playwright/v6-home.png'});
 await nav.getByRole('button',{name:'项目',exact:true}).click();
 const projects=page.getByRole('main',{name:'项目目录'});await projects.waitFor();
 await projects.getByRole('button',{name:'固定项目甲',exact:true}).click();await page.getByRole('navigation',{name:'固定项目'}).waitFor();
 await projects.locator('.directory-open',{hasText:'项目甲'}).click();await page.locator('.conversation-head h1').filter({hasText:'项目甲'}).waitFor();
 await nav.getByRole('button',{name:'项目',exact:true}).click();await projects.locator('.directory-open',{hasText:'项目乙'}).click();
 await page.locator('.conversation-head h1').filter({hasText:'项目乙'}).waitFor();
 await page.locator('.composer textarea').fill('保留在项目乙的输入草稿');
 const modes=page.getByRole('group',{name:'工作区显示方式'});
 await modes.getByRole('button',{name:'AI 全屏',exact:true}).click();assert.equal(await page.locator('.inspector').isVisible(),false);
 await modes.getByRole('button',{name:'AI 半屏',exact:true}).click();await page.locator('.inspector').waitFor();assert.equal(await page.locator('.inspector').isVisible(),true);
 assert.equal(await page.locator('.composer textarea').inputValue(),'保留在项目乙的输入草稿');
 await page.screenshot({path:'output/playwright/v6-project.png'});
 await nav.getByRole('button',{name:'工具',exact:true}).click();await page.getByRole('main',{name:'工具目录'}).waitFor();
 await page.getByRole('button',{name:'医疗工具',exact:true}).click();await page.getByRole('heading',{name:'临床速查',exact:true}).waitFor();
 await page.screenshot({path:'output/playwright/v6-tools.png'});
 assert.equal(await page.getByRole('heading',{name:'浏览器',exact:true}).count(),0);
 assert.equal(await page.getByRole('heading',{name:'终端与代码',exact:true}).count(),0);
 assert.equal(await page.getByRole('heading',{name:'技能与连接',exact:true}).count(),0);
 await nav.getByRole('button',{name:'任务',exact:true}).click();
 const history=page.getByRole('main',{name:'任务记录'});await history.waitFor();
 assert.equal(await history.getByRole('button',{name:/持续任务验收/}).count(),1);
 await history.getByRole('button',{name:/持续任务验收/}).click();await page.locator('.conversation-head h1').filter({hasText:'持续任务验收'}).waitFor();
 await page.locator('.composer textarea').fill('保留独立任务草稿');
 await modes.getByRole('button',{name:'AI 全屏',exact:true}).click();assert.equal(await page.locator('.inspector').isVisible(),false);
 await modes.getByRole('button',{name:'AI 半屏',exact:true}).click();await page.locator('.inspector').waitFor();assert.equal(await page.locator('.inspector').isVisible(),true);
 assert.equal(await page.locator('.composer textarea').inputValue(),'保留独立任务草稿');
 await page.getByRole('button',{name:'Aa · 大字模式',exact:true}).click();
 await page.setViewportSize({width:600,height:900});
 await page.getByRole('button',{name:'打开工作台导航',exact:true}).click();assert.equal(await nav.getByRole('button',{name:'工具',exact:true}).isVisible(),true);
 await nav.getByRole('button',{name:'工具',exact:true}).click();await page.getByRole('main',{name:'工具目录'}).waitFor();
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));await page.screenshot({path:'output/playwright/v6-narrow.png'});
 assert.deepEqual(errors,[]);assert.equal((await f.json('/api/workspaces/'+b.id)).data.title,'项目乙');assert.equal((await f.json('/api/workspaces/'+a.id)).data.pinned,true);assert.equal((await f.json('/api/sessions/'+session.id)).data.title,'持续任务验收');
});
